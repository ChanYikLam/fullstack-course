// =============================================
// 第一部分：变量绑定（let）与 可变性（mut）
// 对比 C++ 的 const 和 普通变量
// =============================================

fn variable_demo() {
    // C++ 写法: const int a = 10;
    // Rust 默认不可变（immutable），相当于自带 const
    let a = 10;
    // a = 20; // 这行解开注释会编译报错：无法给不可变变量赋值
    
    // C++ 写法: int b = 20;
    // Rust 必须显式写 mut 才能改变
    let mut b = 20;
    b = 30; // 允许
    println!("[变量] 不可变 a = {}, 可变 b = {}", a, b);
}

// =============================================
// 第二部分：所有权（Ownership）与 移动（Move）
// 这是 Rust 最颠覆 C++ 习惯的地方！
// 对比 C++ 的拷贝构造函数 / std::move
// =============================================

fn ownership_demo() {
    // Rust 的 String 类似 C++ 的 std::string（堆分配）
    let s1 = String::from("Hello");
    
    // ⚠️ 关键差异：
    // C++ 中: std::string s2 = s1;  --> 拷贝构造（深拷贝）
    // Rust 中: let s2 = s1;         --> 移动语义（Move）
    // s1 的内部指针被“转移”给 s2，s1 立即失效（类似被 move 后的空壳，但更安全）
    let s2 = s1;
    
    // println!("{}", s1); // ❌ 编译错误！s1 的所有权已被移走（use of moved value）
    println!("[所有权] s2 = {}", s2); // ✅ 正常
    
    // 如果你想实现 C++ 那样的深拷贝，必须显式调用 .clone()
    let s3 = s2.clone(); // 此时 s2 依然有效
    println!("[克隆] s2 = {}, s3 = {}", s2, s3);
    
    // 再看函数传参：Rust 默认也是移动（除非使用引用）
    take_ownership(s2); // s2 移动到函数里，之后 s2 就失效了
    // println!("{}", s2); // ❌ 编译错误！
    
    // 对于基础类型（整数、浮点、布尔），Rust 实现的是 Copy 语义（类似 C++ 的浅拷贝/按位拷贝）
    let x = 5;
    let y = x; // 整数实现了 Copy，所以 x 依然有效（不像 String）
    println!("[Copy类型] x = {}, y = {}", x, y);
}

fn take_ownership(s: String) {
    println!("函数拿到了所有权: {}", s);
} // s 在这里被 drop（相当于 C++ 的析构函数自动调用），释放堆内存

// =============================================
// 第三部分：借用（Borrowing）与引用（References）
// 对比 C++ 的 const T& 和 T&，但多了严格的读写规则
// =============================================

fn borrowing_demo() {
    let mut s = String::from("Rust");
    
    // ---- 不可变借用（相当于 C++ 的 const std::string&） ----
    let r1 = &s; // 只能读，不能改
    let r2 = &s; // 允许多个不可变借用同时存在
    println!("[不可变借用] r1 = {}, r2 = {}", r1, r2);
    // r1.push_str("!"); // ❌ 编译错误！不可变引用不能修改
    
    // ---- 可变借用（相当于 C++ 的 std::string&） ----
    let r3 = &mut s; // 只能同时存在一个可变借用
    r3.push_str(" 2026"); // 允许修改
    println!("[可变借用] r3 = {}", r3);
    
    // ⚠️ 大规则：可变借用存在时，绝对不能有其他借用（读也不行）
    // let r4 = &s; // ❌ 如果上一行 r3 还没用完，这行会编译失败
    // 但上面的代码 r3 已经用完了（println 之后没再使用），所以这里可以安全地重新不可变借用
    let r5 = &s;
    println!("[可变已结束] 现在只读 r5 = {}", r5);
}

// =============================================
// 第四部分：函数返回值与所有权（额外加分）
// 对比 C++ 的返回值优化（RVO）和移动语义
// =============================================

fn build_string() -> String {
    let s = String::from("World");
    s // 注意这里没有分号！表示把所有权返回给调用方
}

fn return_demo() {
    let s = build_string(); // s 拿到了所有权，且没有发生任何拷贝（类似 C++ 的 NRVO/移动）
    println!("[返回值] 拿到所有权: {}", s);
}

// =============================================
// 主函数入口
// =============================================

fn main() {
    variable_demo();
    ownership_demo();
    borrowing_demo();
    return_demo();
    
    println!("\n✅ 所有代码运行完毕！注意看编译器的报错注释。");
}